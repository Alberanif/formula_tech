import { test } from 'node:test';
import assert from 'node:assert/strict';
import { randomBytes, randomUUID } from 'node:crypto';
import handler from '../api/game.ts';
import { pool } from '../server/db.js';
import { passwordHash } from '../server/session.js';

test('Neon: sessão, autorização, sala, inscrição e idempotência', async () => {
  const email=`smoke-${randomUUID()}@example.invalid`;
  const password=randomBytes(20).toString('hex');
  const salt=randomBytes(32).toString('hex');
  const teacher=(await pool.query(`insert into public.app_users(role) values('teacher') returning id`)).rows[0].id;
  let student: string|undefined, secondStudent: string|undefined, thirdStudent: string|undefined, roomId: string|undefined;
  const request=async (action:string, payload:any={}, cookie='') => {
    const headers:any={host:'localhost:8787',origin:'http://localhost:8787',cookie};
    const req:any={method:'POST',headers,body:{action,...payload}};
    const res:any={headers:{},statusCode:200,setHeader(key:string,value:string){this.headers[key]=value;},status(code:number){this.statusCode=code;return this;},json(value:any){this.body=value;return this;}};
    await handler(req,res);
    return res;
  };
  try {
    await pool.query('insert into public.teacher_accounts(user_id,email,password_hash,salt) values($1,$2,$3,$4)',[teacher,email,await passwordHash(password,salt),salt]);
    const denied=await request('create-room',{name:'Teste Neon'});
    assert.equal(denied.statusCode,403);
    const login=await request('teacher-login',{email,password});
    assert.equal(login.body.ok,true,JSON.stringify(login.body));
    const teacherCookie=login.headers['Set-Cookie'].split(';')[0];
    const invalidSetup=await request('create-room',{name:'Teste Neon',raceCount:6,lapsPerRace:2},teacherCookie);
    assert.equal(invalidSetup.body.code,'INVALID_RACE_SETUP');
    const created=await request('create-room',{name:'Teste Neon',maxPlayers:2,carsPerHeat:2,raceCount:3,lapsPerRace:4},teacherCookie);
    assert.equal(created.body.ok,true,JSON.stringify(created.body));
    roomId=created.body.data.roomId;
    const studentAuth=await request('student-auth');
    assert.equal(studentAuth.body.ok,true,JSON.stringify(studentAuth.body));
    student=studentAuth.body.data.user.id;
    const studentCookie=studentAuth.headers['Set-Cookie'].split(';')[0];
    const requestId=randomUUID();
    const joined=await request('join-room',{code:created.body.data.code,teamName:'Equipe Teste',color:'#44b6d7',requestId},studentCookie);
    assert.equal(joined.body.ok,true,JSON.stringify(joined.body));
    const repeated=await request('join-room',{code:created.body.data.code,teamName:'Equipe Teste',color:'#44b6d7',requestId},studentCookie);
    assert.deepEqual(repeated.body,joined.body);
    const secondAuth=await request('student-auth');
    secondStudent=secondAuth.body.data.user.id;
    const secondCookie=secondAuth.headers['Set-Cookie'].split(';')[0];
    const duplicate=await request('join-room',{code:created.body.data.code,teamName:'Equipe Teste',color:'#44b6d7',requestId:randomUUID()},secondCookie);
    assert.equal(duplicate.statusCode,400,JSON.stringify(duplicate.body));
    assert.equal(duplicate.body.code,'DUPLICATE_NAME');
    const teacherState=await request('state',{roomId},teacherCookie);
    assert.equal(teacherState.statusCode,200,JSON.stringify(teacherState.body));
    assert.equal(teacherState.body.data.roster.length,1);
    assert.equal(teacherState.body.data.teacherTeams.length,1);
    assert.equal(teacherState.body.data.room.teacherId,teacher);
    assert.equal(teacherState.body.data.room.raceCount,3);
    assert.equal(teacherState.body.data.room.lapsPerRace,4);
    const rooms=await request('teacher-rooms',{},teacherCookie);
    assert.equal(rooms.statusCode,200,JSON.stringify(rooms.body));
    assert.ok(rooms.body.data.rooms.some((room:any)=>room.id===roomId&&room.teamCount===1));
    const studentRooms=await request('teacher-rooms',{},studentCookie);
    assert.equal(studentRooms.statusCode,403);
    const state=await request('state',{roomId},studentCookie);
    assert.equal(state.body.data.roster.length,1);
    assert.equal(state.body.data.own.name,'Equipe Teste');
    const projection=await request('state',{roomId,projectionToken:created.body.data.projectionToken});
    assert.equal(projection.body.data.own,undefined);
    const blocked=await request('rotate-access',{roomId,kind:'code'},studentCookie);
    assert.equal(blocked.statusCode,403);
    const studentRemoval=await request('remove-team',{roomId,teamId:joined.body.data.teamId,requestId:randomUUID()},studentCookie);
    assert.equal(studentRemoval.statusCode,403);
    const removed=await request('remove-team',{roomId,teamId:joined.body.data.teamId,requestId:randomUUID()},teacherCookie);
    assert.equal(removed.statusCode,200,JSON.stringify(removed.body));
    const afterRemoval=await request('state',{roomId},teacherCookie);
    assert.equal(afterRemoval.body.data.roster.length,0);
    assert.equal(afterRemoval.body.data.teacherTeams[0].removed,true);
    const formerMember=await request('state',{roomId},studentCookie);
    assert.equal(formerMember.statusCode,403);
    assert.equal(formerMember.body.code,'TEAM_REMOVED');
    const formerRejoin=await request('join-room',{code:created.body.data.code,teamName:'Outra Equipe',color:'#44b6d7',requestId:randomUUID()},studentCookie);
    assert.equal(formerRejoin.statusCode,403);
    assert.equal(formerRejoin.body.code,'TEAM_REMOVED');
    const replacement=await request('join-room',{code:created.body.data.code,teamName:'Equipe Teste',color:'#44b6d7',requestId:randomUUID()},secondCookie);
    assert.equal(replacement.statusCode,200,JSON.stringify(replacement.body));
    assert.notEqual(replacement.body.data.teamId,joined.body.data.teamId);
    const count=await pool.query('select count(*)::int as total from public.game_audit where room_id=$1',[roomId]);
    assert.equal(count.rows[0].total,3);
    assert.equal((await request('race-speed',{roomId,speed:8,requestId:randomUUID()},secondCookie)).statusCode,403);
    assert.equal((await request('race-speed',{roomId,speed:8,requestId:randomUUID()},teacherCookie)).body.data.speed,8);
    assert.equal((await request('state',{roomId},teacherCookie)).body.data.room.raceSpeed,8);
    const thirdAuth=await request('student-auth');
    thirdStudent=thirdAuth.body.data.user.id;
    const thirdCookie=thirdAuth.headers['Set-Cookie'].split(';')[0];
    const thirdJoin=await request('join-room',{code:created.body.data.code,teamName:'Equipe Extra',requestId:randomUUID()},thirdCookie);
    assert.equal(thirdJoin.statusCode,200,JSON.stringify(thirdJoin.body));
    const roomData=(await pool.query('select data from public.game_rooms where id=$1',[roomId])).rows[0].data;
    roomData.phase='QUALIFYING';
    roomData.qteEnabled=false;
    const heatId=randomUUID();
    roomData.heats=[{id:heatId,type:'qualifier',round:1,laps:1,number:1,status:'running',startAt:Date.now()-2000,pauseTotal:0,pausedAt:null,checkpoint:0,event:null,history:[],incidents:[],duration:1500,participants:[
      {teamId:replacement.body.data.teamId,name:'Equipe Teste',color:'#44b6d7',number:2,base:1000,adjust:0,final:null,rank:null,mixedScore:50,sectorTimes:[]},
      {teamId:thirdJoin.body.data.teamId,name:'Equipe Extra',color:'#f05d5e',number:3,base:1500,adjust:0,final:null,rank:null,mixedScore:50,sectorTimes:[]},
    ]}];
    await pool.query('update public.game_rooms set data=$2::jsonb where id=$1',[roomId,JSON.stringify(roomData)]);
    const finish=await request('sync-race',{roomId,heatId,requestId:randomUUID()},secondCookie);
    assert.equal(finish.statusCode,200,JSON.stringify(finish.body));
    const finished=await request('state',{roomId},secondCookie);
    assert.equal(finished.body.data.heats[0].status,'finished');
    assert.equal(finished.body.data.heats[0].prizes[replacement.body.data.teamId],300);
    assert.equal(finished.body.data.own.wallet,1500);
    const prizes=await pool.query("select team_id,amount_signed from public.financial_events where room_id=$1 and action='race_prize'",[roomId]);
    assert.equal(prizes.rows.length,2);
    assert.deepEqual(prizes.rows.map((x:any)=>x.amount_signed).sort((a:number,b:number)=>a-b),[240,300]);
    await request('sync-race',{roomId,heatId,requestId:randomUUID()},secondCookie);
    const repeatedPrizes=await pool.query("select count(*)::int as total from public.financial_events where room_id=$1 and action='race_prize'",[roomId]);
    assert.equal(repeatedPrizes.rows[0].total,2);
    const left=await request('leave-room',{roomId,requestId:randomUUID()},secondCookie);
    assert.equal(left.statusCode,200,JSON.stringify(left.body));
    assert.equal(left.body.data.left,true);
    assert.equal((await request('state',{roomId},secondCookie)).body.code,'TEAM_LEFT');
    assert.equal((await request('state',{roomId},teacherCookie)).body.data.roster.length,1);
    const deniedDelete=await request('delete-room',{roomId,requestId:randomUUID()},secondCookie);
    assert.equal(deniedDelete.statusCode,403);
    const deleteRequestId=randomUUID();
    const deleted=await request('delete-room',{roomId,requestId:deleteRequestId},teacherCookie);
    assert.equal(deleted.statusCode,200,JSON.stringify(deleted.body));
    assert.equal(deleted.body.data.deleted,true);
    const deleteRetry=await request('delete-room',{roomId,requestId:deleteRequestId},teacherCookie);
    assert.deepEqual(deleteRetry.body,deleted.body);
    const roomsAfterDelete=await request('teacher-rooms',{},teacherCookie);
    assert.ok(!roomsAfterDelete.body.data.rooms.some((room:any)=>room.id===roomId));
    assert.equal((await request('state',{roomId},teacherCookie)).body.code,'ROOM_NOT_FOUND');
    assert.equal((await request('state',{roomId,projectionToken:created.body.data.projectionToken})).body.code,'ROOM_NOT_FOUND');
    assert.equal((await request('join-room',{code:created.body.data.code,teamName:'Outra',requestId:randomUUID()},thirdCookie)).body.code,'ROOM_NOT_FOUND');
  } finally {
    if (roomId) await pool.query('delete from public.game_rooms where id=$1',[roomId]);
    if (thirdStudent) await pool.query('delete from public.app_users where id=$1',[thirdStudent]);
    if (secondStudent) await pool.query('delete from public.app_users where id=$1',[secondStudent]);
    if (student) await pool.query('delete from public.app_users where id=$1',[student]);
    await pool.query('delete from public.app_users where id=$1',[teacher]);
    await pool.end();
  }
});
